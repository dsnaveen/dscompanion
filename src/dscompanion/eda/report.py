        dup_df = df[df.duplicated(keep=False)].copy()
        if dup_df.empty:
            return dup_df
        cols = list(df.columns)
        dup_df["_dup_count"] = dup_df.groupby(cols, dropna=False)[cols[0]].transform("size")
