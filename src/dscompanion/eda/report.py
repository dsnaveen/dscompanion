    def overview_summary(self) -> dict[str, Any]:
        """Return high-level dataset statistics: rows, columns, missing cells, duplicate rows.

        Computed directly from ``split.train_X`` — independent of which
        individual analysers ran, so it is always available once
        ``run_all()`` has been called.

        Args:
            None

        Returns:
            dict[str, Any]: ``{"total_rows": int, "total_columns": int,
            "total_missing": int, "missing_pct": float, "duplicate_rows":
            int, "duplicate_pct": float}``.

        Raises:
            RuntimeError: If ``run_all`` has not been called yet.
        """
        self._check_run()
        df = self._split.train_X
        total_rows, total_cols = df.shape
        total_cells = total_rows * total_cols
        total_missing = int(df.isna().sum().sum())
        duplicate_rows = int(df.duplicated().sum())
        return {
            "total_rows": total_rows,
            "total_columns": total_cols,
            "total_missing": total_missing,
            "missing_pct": round(100 * total_missing / max(total_cells, 1), 2),
            "duplicate_rows": duplicate_rows,
            "duplicate_pct": round(100 * duplicate_rows / max(total_rows, 1), 2),
        }

