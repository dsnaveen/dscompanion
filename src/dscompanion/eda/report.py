    def alerts(self) -> dict[str, list[dict[str, str]]]:
        """Return a unified, per-feature list of data-quality alerts.

        Aggregates signals already computed by all three analysers into a
        single rendering-friendly structure — complements (does not
        replace) ``flagged_features()``/``recommended_drops``, which remain
        the programmatic "what to drop" API.  Wires in
        ``BivariateAnalyser.flag_high_correlation()``, which previously had
        no caller anywhere in the reporting layer.

        Args:
            None

        Returns:
            dict[str, list[dict[str, str]]]: Keyed by feature name, each
            value a list of ``{"type": str, "detail": str}`` dicts.
            ``type`` is one of the ``EDAAlert.*`` constants.  Features with
            no alerts are absent from the dict (not present with an empty
            list).

        Raises:
            RuntimeError: If ``run_all`` has not been called yet.
        """
        self._check_run()
        num_df = self._uni.numeric_summary()
        cat_df = self._uni.categorical_summary()
        iv_df = self._bi.iv_table()
        multicollinear = set(self._multi.flag_multicollinearity())
        high_corr = self._bi.flag_high_correlation()

        result: dict[str, list[dict[str, str]]] = {}

        def _add(feature: str, atype: str, detail: str) -> None:
            result.setdefault(feature, []).append({"type": atype, "detail": detail})

        for _, r in num_df.iterrows():
            f = r["feature"]
            if r["missing_pct"] > self._high_missing_threshold:
                _add(f, EDAAlert.HIGH_MISSING, f"{r['missing_pct'] * 100:.1f}% missing")
            if bool(r["constant_flag"]):
                _add(f, EDAAlert.CONSTANT, "zero variance")
            if bool(r["near_zero_variance_flag"]):
                _add(f, EDAAlert.NEAR_ZERO_VARIANCE, "variance below threshold")
            if pd.notna(r["skewness"]) and abs(r["skewness"]) >= self._skewness_alert_threshold:
                _add(f, EDAAlert.SKEWED, f"skewness={r['skewness']:.2f}")
            if r["zero_pct"] >= self._zero_pct_alert_threshold:
                _add(f, EDAAlert.ZEROS, f"{r['zero_pct'] * 100:.1f}% zeros")

        for _, r in cat_df.iterrows():
            f = r["feature"]
            if r["missing_pct"] > self._high_missing_threshold:
                _add(f, EDAAlert.HIGH_MISSING, f"{r['missing_pct'] * 100:.1f}% missing")
            if bool(r["cardinality_flag"]):
                _add(f, EDAAlert.HIGH_CARDINALITY, f"{r['n_unique']} unique values")
            if r["n_unique"] <= 1:
                _add(f, EDAAlert.CONSTANT, "single value")
            imb = r.get("imbalance")
            if imb is not None and pd.notna(imb) and imb >= self._imbalance_alert_threshold:
                _add(f, EDAAlert.IMBALANCED, f"imbalance score={imb:.2f}")

        for _, r in iv_df.iterrows():
            if r["iv"] < settings.iv_threshold:
                _add(r["feature"], EDAAlert.LOW_IV, f"IV={r['iv']:.4f}")

        for f in multicollinear:
            _add(f, EDAAlert.MULTICOLLINEAR, "VIF exceeds threshold")

        for _, r in high_corr.iterrows():
            _add(
                r["feature_a"],
                EDAAlert.HIGH_CORRELATION,
                f"r={r['pearson_r']} with {r['feature_b']}",
            )
            _add(
                r["feature_b"],
                EDAAlert.HIGH_CORRELATION,
                f"r={r['pearson_r']} with {r['feature_a']}",
            )

        return result

