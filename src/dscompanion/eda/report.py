class EDAReport:
    """Orchestrate univariate, bivariate, and multivariate EDA analysers and expose a
    unified reporting API.

    Acts as a facade over ``UnivariateAnalyser``, ``BivariateAnalyser``, and
    ``MultivariateAnalyser``.  Calling ``run_all`` fits each analyser in
    sequence on the provided DataSplit and stores the fitted objects internally.
    Subsequent methods delegate to those objects to produce HTML reports,
    Databricks notebook displays, feature-flag dictionaries, and drop
    recommendations.  No side-effects outside this instance; does not mutate
    the DataSplit.

    Args:
        split: A ``DataSplit`` instance that exposes ``train_X``
            (``pandas.DataFrame``), ``train_y`` (``pandas.Series``), and a
            ``metadata`` object with a ``strategy`` attribute.
        target (str): Name of the target column.  Used as a label in the
            HTML report overview section and must correspond to the binary
            target variable used during DataSplit construction.
        high_missing_threshold (float): Missing-value rate above which
            ``alerts()`` raises a ``HIGH_MISSING`` alert for a feature.  A
            value of ``0`` delegates to ``settings.high_missing_threshold``.
        near_zero_variance_threshold (float): Variance below which a numeric
            feature is flagged ``near_zero_variance_flag`` (and, via
            ``recommended_drops``/``recommended_drops_with_reasons``,
            suggested for removal).  A value of ``0`` delegates to
            ``settings.near_zero_variance_threshold``.
        skewness_alert_threshold (float): Absolute skewness at-or-above
            which ``alerts()`` raises a ``SKEWED`` alert for a numeric
            feature.  A value of ``0`` delegates to
            ``settings.eda_skewness_alert_threshold``.
        zero_pct_alert_threshold (float): Zero-value rate at-or-above which
            ``alerts()`` raises a ``ZEROS`` alert for a numeric feature.  A
            value of ``0`` delegates to ``settings.eda_zero_pct_alert_threshold``.
        imbalance_alert_threshold (float): Entropy-based imbalance score
            at-or-above which ``alerts()`` raises an ``IMBALANCED`` alert
            for a categorical feature.  A value of ``0`` delegates to
            ``settings.eda_imbalance_alert_threshold``.
        extreme_values_n (int): Number of smallest/largest raw values
            captured per numeric feature by ``extreme_values()``.  A value
            of ``0`` delegates to ``settings.eda_extreme_values_n``.
        sample_n_rows (int): Rows shown per head/tail by ``sample_rows()``.
            A value of ``0`` delegates to ``settings.eda_sample_n_rows``.
        duplicate_rows_max_display (int): Cap on rows returned by
            ``duplicate_row_content()``.  A value of ``0`` delegates to
            ``settings.eda_duplicate_rows_max_display``.
        missing_matrix_max_rows (int): Row subsample cap for
            ``missing_matrix()``.  A value of ``0`` delegates to
            ``settings.eda_missing_matrix_max_rows``.
        interaction_max_numeric_cols (int): Cap on numeric columns
            considered by ``interaction_plots()``.  A value of ``0``
            delegates to ``settings.eda_interaction_max_numeric_cols``.
        interaction_hexbin_row_threshold (int): Row count above which
            ``interaction_plots()`` switches from scatter to hexbin.  A
            value of ``0`` delegates to
            ``settings.eda_interaction_hexbin_row_threshold``.
        text_analysis_top_n_words (int): Top-N word-frequency entries
            captured by ``word_frequency()``.  A value of ``0`` delegates to
            ``settings.eda_text_analysis_top_n_words``.
        text_analysis_top_n_chars (int): Top-N character-frequency entries
            captured by ``character_frequency()``.  A value of ``0``
            delegates to ``settings.eda_text_analysis_top_n_chars``.
        include_sample_rows (bool): Compliance opt-in for ``sample_rows()``
            output.  Defaults to ``False``.
        include_duplicate_row_content (bool): Compliance opt-in for
            ``duplicate_row_content()`` output.  Defaults to ``False``.
        include_text_sample_values (bool): Compliance opt-in for raw
            sample-value exposure in ``word_frequency()``/
            ``character_frequency()`` output.  Defaults to ``False``.

    Example::

        report = EDAReport(split, target="default_flag").run_all()
        report.to_html("eda.html")
        print(report.recommended_drops)
    """

    def __init__(
        self,
        split: Any,
        target: str,
        high_missing_threshold: float = 0.0,
        near_zero_variance_threshold: float = 0.0,
        skewness_alert_threshold: float = 0.0,
        zero_pct_alert_threshold: float = 0.0,
        imbalance_alert_threshold: float = 0.0,
        extreme_values_n: int = 0,
        sample_n_rows: int = 0,
        duplicate_rows_max_display: int = 0,
        missing_matrix_max_rows: int = 0,
        interaction_max_numeric_cols: int = 0,
        interaction_hexbin_row_threshold: int = 0,
        text_analysis_top_n_words: int = 0,
        text_analysis_top_n_chars: int = 0,
        include_sample_rows: bool = False,
        include_duplicate_row_content: bool = False,
        include_text_sample_values: bool = False,
    ) -> None:  # Any: DataSplit — avoids circular import
        self._split = split
        self._target = target
        self._high_missing_threshold = high_missing_threshold or settings.high_missing_threshold
        self._near_zero_variance_threshold = (
            near_zero_variance_threshold or settings.near_zero_variance_threshold
        )
        self._skewness_alert_threshold = (
            skewness_alert_threshold or settings.eda_skewness_alert_threshold
        )
        self._zero_pct_alert_threshold = (
            zero_pct_alert_threshold or settings.eda_zero_pct_alert_threshold
        )
        self._imbalance_alert_threshold = (
            imbalance_alert_threshold or settings.eda_imbalance_alert_threshold
        )
        self._extreme_values_n = extreme_values_n or settings.eda_extreme_values_n
        self._sample_n_rows = sample_n_rows or settings.eda_sample_n_rows
        self._duplicate_rows_max_display = (
            duplicate_rows_max_display or settings.eda_duplicate_rows_max_display
        )
        self._missing_matrix_max_rows = (
            missing_matrix_max_rows or settings.eda_missing_matrix_max_rows
        )
        self._interaction_max_numeric_cols = (
            interaction_max_numeric_cols or settings.eda_interaction_max_numeric_cols
        )
        self._interaction_hexbin_row_threshold = (
            interaction_hexbin_row_threshold or settings.eda_interaction_hexbin_row_threshold
        )
        self._text_analysis_top_n_words = (
            text_analysis_top_n_words or settings.eda_text_analysis_top_n_words
        )
        self._text_analysis_top_n_chars = (
            text_analysis_top_n_chars or settings.eda_text_analysis_top_n_chars
        )
        self._include_sample_rows = include_sample_rows
        self._include_duplicate_row_content = include_duplicate_row_content
        self._include_text_sample_values = include_text_sample_values
        self._uni: UnivariateAnalyser | None = None
        self._bi: BivariateAnalyser | None = None
        self._multi: MultivariateAnalyser | None = None
        self._missing: MissingnessAnalyser | None = None

    def run_all(self) -> "EDAReport":
        """Fit univariate, bivariate, and multivariate analysers in sequence on the
        stored DataSplit.

        Instantiates a fresh ``UnivariateAnalyser``, ``BivariateAnalyser``,
        and ``MultivariateAnalyser``, calling ``fit(self._split)`` on each in
        order.  Logs INFO messages at the start of each stage and on
        completion.  After this method returns, all accessor methods and
        properties on this instance become available.

        Args:
            None

        Returns:
            EDAReport: This instance, allowing method chaining
            (e.g. ``EDAReport(split, "target").run_all().to_html("out.html")``).
        """
        logger.info("EDAReport.run_all — starting univariate")
        self._uni = UnivariateAnalyser(
            high_missing_threshold=self._high_missing_threshold,
            near_zero_variance_threshold=self._near_zero_variance_threshold,
        ).fit(self._split)

        logger.info("EDAReport.run_all — bivariate")
        self._bi = BivariateAnalyser(
            interaction_max_numeric_cols=self._interaction_max_numeric_cols,
            interaction_hexbin_row_threshold=self._interaction_hexbin_row_threshold,
        ).fit(self._split)

        logger.info("EDAReport.run_all — multivariate")
        self._multi = MultivariateAnalyser().fit(self._split)

        logger.info("EDAReport.run_all — missingness")
        self._missing = MissingnessAnalyser(max_rows=self._missing_matrix_max_rows).fit(self._split)

        logger.info("EDAReport.run_all — complete")
        return self

    def to_html(self, path: str | Path) -> Path:
        """Render the complete EDA report to a self-contained HTML file and return its
        resolved path.

        Builds a Jinja2 template context from the numeric summary, IV table,
        and data quality flags, then writes a single UTF-8 encoded HTML file
        to the specified path.  The file can be opened directly in a browser
        with no external dependencies.  Parent directories must already exist;
        this method does not create them.  Logs an INFO message with the
        resolved path after writing.

        Args:
            path (str | pathlib.Path): Destination file path.  Relative paths
                are resolved relative to the current working directory.
                Existing files at this path are silently overwritten.

        Returns:
            pathlib.Path: The resolved (absolute) ``Path`` object of the
            written HTML file.

        Raises:
            RuntimeError: If ``run_all`` has not been called yet.
        """
        self._check_run()
        path = Path(path)

        num_df = self._uni.numeric_summary()
        iv_df = self._bi.iv_table()
        issues = self._uni.flag_issues()

        flagged_rows = []
        for _, row in issues.iterrows():
            for issue in ["high_missing", "near_zero_variance", "high_cardinality", "constant"]:
                if row.get(issue):
                    flagged_rows.append(
                        {"feature": row["feature"], "issue": issue.replace("_", " ")}
                    )

        overview = {
            "Train rows": f"{len(self._split.train_X):,}",
            "Columns": len(self._split.train_X.columns),
            "Target": self._target,
            "Strategy": self._split.metadata.strategy,
        }

        num_cols = num_df.columns.tolist() if len(num_df) > 0 else []
        num_rows = [row.tolist() for _, row in num_df.iterrows()]

        from jinja2 import Template

        html = Template(_HTML_TEMPLATE).render(
            title="EDA Report — dscompanion",
            overview=overview,
            num_cols=num_cols,
            num_rows=num_rows,
            iv_rows=iv_df.to_dict("records"),
            flagged_rows=flagged_rows,
        )
        path.write_text(html, encoding="utf-8")
        logger.info("EDA report saved → %s", path)
        return path

    def to_databricks_display(self) -> None:
        """Render and display the EDA report inline in a Databricks notebook, or write
        it to a local HTML file outside Databricks.

        When running inside a Databricks notebook (detected via
        ``dscompanion.utils.validators.is_databricks``), the report is first
        written to ``/tmp/eda_report.html`` and then rendered inline using
        the Databricks built-in ``displayHTML`` function.  When running
        outside Databricks the report is written to ``eda_report.html`` in
        the current working directory via ``to_html`` as a fallback.

        Args:
            None

        Returns:
            None

        Raises:
            RuntimeError: If ``run_all`` has not been called yet.
        """
        self._check_run()
        if is_databricks():
            # A uniquely-named tempfile.NamedTemporaryFile, not a fixed
            # "/tmp/eda_report.html" path -- Databricks clusters can run multiple
            # users' notebooks concurrently, and a predictable shared-/tmp filename
            # is a symlink/race-condition risk (Bandit B108, a genuine finding here,
            # not a false positive). Cleaned up afterward either way.
            with tempfile.NamedTemporaryFile(suffix=".html", delete=False) as tmp_file:
                tmp = Path(tmp_file.name)
            try:
                self.to_html(tmp)
                html = tmp.read_text()
                displayHTML(html)  # noqa: F821  # Databricks built-in
            finally:
                tmp.unlink(missing_ok=True)
        else:
            self.to_html("eda_report.html")

    def flagged_features(self) -> dict[str, list[str]]:
        """Return a dictionary grouping feature names by their data quality issue category.

        Aggregates flags from all three analysers.  ``constant`` and
        ``high_missing`` originate from the univariate analyser.  ``low_iv``
        is derived from the bivariate IV table using ``settings.iv_threshold``
        as the cutoff.  ``multicollinear`` comes from the multivariate
        analyser's VIF computation.

        Args:
            None

        Returns:
            dict[str, list[str]]: A dictionary with four keys — ``"constant"``
            (features with zero or one unique value), ``"high_missing"``
            (features with more than 30 % null values), ``"low_iv"`` (features
            whose IV falls below ``settings.iv_threshold``), and
            ``"multicollinear"`` (features whose VIF exceeds
            ``settings.vif_threshold``).  Any list may be empty when no
            features fall into that category.

        Raises:
            RuntimeError: If ``run_all`` has not been called yet.
        """
        self._check_run()
        issues = self._uni.flag_issues()
        iv_df = self._bi.iv_table()
        mc = self._multi.flag_multicollinearity()

        return {
            "constant": issues.loc[issues["constant"], "feature"].tolist(),
            "high_missing": issues.loc[issues["high_missing"], "feature"].tolist(),
            "low_iv": iv_df.loc[iv_df["iv"] < settings.iv_threshold, "feature"].tolist(),
            "multicollinear": mc,
        }

    @property
    def recommended_drops(self) -> list[str]:
        """Return a sorted list of column names that are safe to drop based on
        constancy, near-zero variance, and low IV.

        Combines three sources: features flagged as constant by the univariate
        analyser, features with IV below ``settings.iv_threshold`` from the
        bivariate analyser, and numeric features with near-zero variance
        (``near_zero_variance_flag=True``) from the numeric summary.  The union
        of these three sets is returned as a sorted list, so the result is
        deterministic regardless of insertion order.

        Args:
            None

        Returns:
            list[str]: Sorted list of column names recommended for removal.
            Returns an empty list when no features meet any of the three
            criteria.

        Raises:
            RuntimeError: If ``run_all`` has not been called yet.
        """
        self._check_run()
        flagged = self.flagged_features()
        drops = set(flagged["constant"]) | set(flagged["low_iv"])
        # Add near-zero variance
        num_summary = self._uni.numeric_summary()
        if len(num_summary) > 0:
            nzv = num_summary.loc[num_summary["near_zero_variance_flag"], "feature"].tolist()
            drops.update(nzv)
        return sorted(drops)

    def recommended_drops_with_reasons(self) -> dict[str, list[str]]:
        """Return ``recommended_drops``'s same column set, with each column's reason(s) attached.

        Same three sources as ``recommended_drops`` — constant, near-zero
        variance, low IV — but returned as a mapping so a caller (e.g. the
        Interactive-mode Step 5 UI) can show *why* a column is suggested for
        removal, not just that it is.

        Args:
            None

        Returns:
            dict[str, list[str]]: Column name -> sorted list of reasons
            drawn from ``{"constant", "near_zero_variance", "low_iv"}``.
            Sorted by column name; a column may have more than one reason.
            Returns an empty dict when no features meet any criterion.

        Raises:
            RuntimeError: If ``run_all`` has not been called yet.
        """
        self._check_run()
        flagged = self.flagged_features()
        num_summary = self._uni.numeric_summary()
        nzv_cols = (
            set(num_summary.loc[num_summary["near_zero_variance_flag"], "feature"])
            if len(num_summary) > 0
            else set()
        )

        reasons: dict[str, set[str]] = {}
        for col in flagged["constant"]:
            reasons.setdefault(col, set()).add("constant")
        for col in nzv_cols:
            reasons.setdefault(col, set()).add("near_zero_variance")
        for col in flagged["low_iv"]:
            reasons.setdefault(col, set()).add("low_iv")

        return {col: sorted(reasons[col]) for col in sorted(reasons)}

    def iv_table(self) -> pd.DataFrame:
        """Return the bivariate Information Value table, sorted by descending IV.

        Thin public delegate over the fitted ``BivariateAnalyser``, exposing
        per-feature predictive power so callers (e.g. ``ModelCard``) don't
        need to reach into the private ``_bi`` attribute.

        Args:
            None

        Returns:
            pd.DataFrame: One row per feature, columns ``feature``, ``iv``,
            ``n_bins``, ``predictive_power``, sorted by ``iv`` descending
            (the underlying ``BivariateAnalyser.iv_table()`` is pre-sorted).

        Raises:
            RuntimeError: If ``run_all`` has not been called yet.
        """
        self._check_run()
        return self._bi.iv_table()

